#!/usr/bin/env node
// report.mjs: regenerate the private probe record,
// ~/.claude/docs/plans/our-setup/probes.md, from passes.json and each
// probe's result.json.
//
//   node report.mjs [--notes <json>] [--doc <file>]
//
// Only the block between <!-- generated:begin --> and <!-- generated:end -->
// is rewritten: whatever sits outside it (the evidence later units record by
// hand) survives. A missing file is created with a short header around the
// block; a file with no block is refused, never overwritten. --notes is a
// JSON object of per-probe design notes ({"Q1": "what it means for the
// design"}), default <flow>/notes.json when that exists. An explicit --doc
// inside a git work tree is refused (refuseTrackedDoc).
//
// A verdict is shown as passes.json files it, marked when its result.json is
// missing or says otherwise, when its def or instrument changed since
// (passedOn's rule), or when two measured runs of one def disagreed (the
// `seen` list writePasses keeps, by run.mjs's measured()). It runs under the
// passes.json lock, so a report never interleaves with a run filing verdicts.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { scrubber } from './lib.mjs';
import { DEFS, EXPECTED, FLOW_PROBES, LOAD_BEARING, defFiles, gitView, judge, passCheck, probesOf, replaceFile, withLock } from './run.mjs';

export const DOC = path.join(os.homedir(), '.claude', 'docs', 'plans', 'our-setup', 'probes.md');
export const BEGIN = '<!-- generated:begin -->';
export const END = '<!-- generated:end -->';

// A verdict judge() voids, and the mark the record shows for it.
const MARKS = {
  'missing def': 'DEF MISSING',
  'recorded before hashing': 'UNHASHED (filed before verdicts carried a hash)',
  'def changed since its verdict': 'STALE (def or instrument changed since)',
  'verdicts disagree on the same def': 'CONFLICT (runs of this def disagreed)',
};

const HEADER = [
  '# Our-setup platform probes (U2)',
  '',
  'Each probe settles one platform behavior the flow design relies on, by running throwaway headless Claude Code sessions and reading what their hooks saw. Code: `projects/hooks/probes/` (public). Results: `~/.claude/flow/probes/<version>/<stamp>/` (private).',
  '',
  'Run a probe when a unit that depends on its answer is built or landed (`cd "$TEMP" && node <repo>/projects/hooks/probes/run.mjs --only <ids>`), then `node <repo>/projects/hooks/probes/report.mjs` and `run.mjs --cleanup <run dir>`; not after every CLI update (Briggsy, 2026-10-27: nothing live reads the verdicts yet). The block below is generated from `passes.json` and the run folders; do not hand-edit it. Record anything else outside it. KTD 10: the gate, once built, enforces only on a version where `passedOn(version)` (run.mjs) returns true; `passCheck(version)` lists the probes that fail it and why.',
  '',
].join('\n');

const fwd = (p) => String(p).replace(/\\/g, '/');
const cell = (s) => String(s ?? '').replace(/\s*\n\s*/g, ' ').replace(/\|/g, '\\|');
const item = (s) => String(s ?? '').replace(/\n/g, '\n    ');
const semverDesc = (a, b) => {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) if (pa[i] !== pb[i]) return (pb[i] || 0) - (pa[i] || 0);
  return 0;
};

function readResult(e, id) {
  if (!e?.run) return null;
  try {
    return JSON.parse(fs.readFileSync(path.join(e.run, id, 'result.json'), 'utf8'));
  } catch {
    return null;
  }
}

// The marks after a probe's verdict ('' when it stands as filed).
function marksFor(id, e, r, files) {
  const marks = [];
  const why = judge(e, files[id]);
  if (MARKS[why] && (e || why === 'missing def')) marks.push(MARKS[why]);
  if (e && !r) marks.push('RESULT MISSING (no result.json in its run folder)');
  else if (e && r && r.verdict !== e.verdict) marks.push(`RESULT SAYS ${r.verdict}`);
  return marks.length ? ` — ${marks.join('; ')}` : '';
}

// The generated block's text, between the markers.
export function renderBlock(passes, { defs = DEFS, notes = {}, scrub = scrubber() } = {}) {
  const files = defFiles(defs);
  const lines = [`_Generated by \`projects/hooks/probes/report.mjs\` at ${new Date().toISOString()}._`, ''];
  for (const version of Object.keys(passes).sort(semverDesc)) {
    const entry = passes[version];
    const probes = probesOf(entry);
    const now = passCheck(version, { defs, passes });
    const failing = now.failing.map((f) => `${f.id} ${f.why === 'not VERIFIED' ? f.verdict : f.why}`).join(', ');
    const filedAs = typeof entry.loadBearingPassed === 'boolean' && entry.loadBearingPassed !== now.passed ? ` (passes.json filed it as ${entry.loadBearingPassed ? 'passed' : 'not passed'}; the files on disk changed since)` : '';
    lines.push(`## CLI ${version}`, '');
    lines.push(`Load-bearing set (pinned in run.mjs): ${LOAD_BEARING.join(', ')}. Passes now: **${now.passed ? 'yes' : 'no'}**${now.passed ? '' : ` (${failing})`}${filedAs}.`, '');
    lines.push('| ID | Verdict | Load-bearing | Question |', '|---|---|---|---|');
    const rows = EXPECTED.map((id) => {
      const e = probes[id];
      const r = readResult(e, id);
      return { id, e, r, verdict: `${e?.verdict ?? 'not run'}${marksFor(id, e, r, files)}` };
    });
    for (const { id, r, verdict } of rows) lines.push(`| ${id} | ${cell(verdict)} | ${LOAD_BEARING.includes(id) ? 'yes' : 'no'} | ${cell(r?.question)} |`);
    lines.push('');
    for (const { id, e, r, verdict } of rows) {
      lines.push(`### ${id}: ${verdict}`, '');
      if (r) {
        lines.push(`- **Question:** ${item(r.question)}`);
        lines.push(`- **Assumption tested:** ${item(r.assumption)}`);
        lines.push(`- **Finding:** ${item(scrub(r.summary))}`);
      }
      if (notes[id]) lines.push(`- **What it means for the design:** ${item(notes[id])}`);
      if (e?.run) lines.push(`- **Run:** \`${scrub(fwd(path.join(e.run, id)))}\`${r ? ` (CLI ${r.version}, ${Math.round((r.ms ?? 0) / 1000)} s)` : ''}`);
      if (r) {
        lines.push('- **Evidence:**');
        for (const ev of r.evidence ?? []) {
          // A long line is cut, and says so: result.json keeps it whole.
          const s = scrub(ev);
          lines.push(`  - ${item(s.length > 1200 ? `${s.slice(0, 1200)} ... (cut at 1200 of ${s.length} characters; the whole line is in result.json)` : s)}`);
        }
      }
      lines.push('');
    }
  }
  return lines.join('\n');
}

// `doc` with its generated block replaced by `block`. Throws on a document
// with no block, or with markers out of order or repeated.
export function spliceBlock(doc, block) {
  const b = doc.indexOf(BEGIN);
  const e = doc.indexOf(END);
  if (b < 0 && e < 0) throw new Error(`no generated block: add ${BEGIN} and ${END} around the part report.mjs may rewrite, or move the file aside to start a new one`);
  if (b < 0 || e < b || doc.indexOf(BEGIN, b + 1) >= 0 || doc.indexOf(END, e + 1) >= 0) throw new Error(`the generated block's markers are missing, repeated or out of order: want one ${BEGIN} before one ${END}`);
  return `${doc.slice(0, b + BEGIN.length)}\n${block.trim()}\n${doc.slice(e)}`;
}

// Regenerate `doc` under the passes.json lock. Returns {doc, versions, marked}.
export async function writeReport({ root = FLOW_PROBES, defs = DEFS, doc = DOC, notesFile } = {}) {
  const passesFile = path.join(root, 'passes.json');
  if (!fs.existsSync(passesFile)) throw new Error(`no passes.json in ${root}: run the probes first`);
  // An explicit --notes file must exist; the default one is optional.
  const nf = notesFile ?? path.join(root, 'notes.json');
  const notes = (notesFile || fs.existsSync(nf)) ? JSON.parse(fs.readFileSync(nf, 'utf8')) : {};
  if (!notes || typeof notes !== 'object' || Array.isArray(notes)) throw new Error(`${nf} is not a JSON object of per-probe notes`);
  return withLock(passesFile, async () => {
    const passes = JSON.parse(fs.readFileSync(passesFile, 'utf8'));
    const block = renderBlock(passes, { defs, notes });
    const current = fs.existsSync(doc) ? fs.readFileSync(doc, 'utf8') : `${HEADER}\n${BEGIN}\n${END}\n`;
    const next = spliceBlock(current, block);
    fs.mkdirSync(path.dirname(doc), { recursive: true });
    await replaceFile(doc, next);
    return { doc, versions: Object.keys(passes).length, marked: (block.match(/^\| Q\d+ \| [^|]* — /gm) ?? []).length };
  });
}

function parseArgs(argv) {
  const a = {};
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    const v = argv[i + 1];
    if (k === '--notes') { a.notesFile = v; i++; }
    else if (k === '--doc') { a.doc = v; i++; }
    else throw new Error(`unknown argument ${k}`);
  }
  return a;
}

// An explicit --doc must sit outside every git work tree, as run.mjs's --out
// must: the scrubber aliases session UUIDs, API ids and paths, but the
// workflow and agent ids and transcript keys a finding quotes stay. The
// default DOC is never checked: it lives in ~/.claude's local-only repo, which
// tracks docs/** on purpose. Kept out of writeReport, whose tests write their
// docs to temp folders.
function refuseTrackedDoc(doc) {
  if (doc !== undefined && gitView(path.dirname(path.resolve(doc))) !== 'outside') {
    throw new Error(`--doc ${doc} is inside a git work tree; the record quotes workflow and agent ids and transcript keys the scrubber keeps, so pick a file outside every repo, or drop --doc for the default`);
  }
}

// import.meta.main (Node >= 24.2): true only when this file is the one node
// ran, symlink or junction included.
if (import.meta.main) {
  Promise.resolve().then(() => {
    const a = parseArgs(process.argv.slice(2));
    refuseTrackedDoc(a.doc);
    return writeReport(a);
  }).then(
    (r) => console.log(`wrote ${r.doc}: ${r.versions} CLI version(s), ${r.marked} marked verdict(s)`),
    (e) => {
      console.error(e.stack || e);
      process.exitCode = 1;
    },
  );
}
