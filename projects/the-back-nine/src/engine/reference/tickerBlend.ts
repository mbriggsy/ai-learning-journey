/**
 * The bundled ticker → asset-class blend reference table (R37; C1 unit, plan §5).
 *
 * One row per issuer SHARE-CLASS FAMILY (VTI == VTSAX — one strategy, one row): the
 * {stock, bond, cash} allocation intake uses to collapse per-ticker holdings into
 * the single household blend feeding the engine's one `stockWeight` (cash folds into
 * the bond sleeve — the engine is 2-asset, v1; plan §5). Rows are DIRECTIONAL
 * issuer-cited snapshots; SEC EDGAR N-PORT is the independent re-derivation path at
 * the pin pass (DND/012). Target-date funds are STATIC snapshots ("today's
 * allocation, held constant" — the user-facing disclosure string is owned by D1;
 * the years-to-target glide curve is the named correctness upgrade).
 *
 * Allocations are the issuer's OWN figures, never renormalized: a balanced/TDF row
 * may sum to ~97–101 (the issuer's "other" sleeve — preferreds/convertibles — plus
 * rounding); {@link stockWeightForBlend} divides by the actual sum, which
 * distributes the residual pro-rata. An unrecognized ticker returns `undefined`
 * from {@link findBlendRow} — intake routes it to the manual 3-choice classifier
 * (D1); NEVER a default blend (burned/062).
 *
 * Generated programmatically from the C1 research artifact (8-agent two-source
 * verification, 2026-06-10, run wf_9e271ad3) — no hand retyping (insight 018's
 * programmatic-transplant discipline). Two low-confidence rows (SSCKX, JBYSX —
 * inference, not citation) were DROPPED, not guessed; their tickers fall through
 * to the manual classifier until the pin pass sources them from EDGAR.
 *
 * PIN PASS (2026-06-11, run wf_2483859a): all 161 families verified against SEC
 * primaries (485BPOS/N-PORT; issuer page only where no EDGAR registrant exists) —
 * 146 rows stood (6 of those survived adjudication, incl. two where a blind
 * reader mistook reinvested securities-lending cash COLLATERAL for a strategic
 * cash sleeve); 15 rows corrected from the N-PORT/prospectus look-through. PINNED
 * rows store the NORMALIZED look-through as {stock, 100−stock, cash:0} — the raw
 * reconstruction (cash/commodity sleeves, accession) lives in the citation. The
 * numerator convention, uniform: a fund is stock by what it HOLDS — REIT/resource-
 * EQUITY funds are stock (T. Rowe Real Assets, SPDR DJ Global Real Estate);
 * commodity-FUTURES sleeves are not stock and have no third home in a 2-asset
 * engine, so they ride the denominator (≤3.5% on any affected row, recorded
 * per-row). N-PORT assetCat is NEVER trusted for fund-of-funds (it tags bond
 * funds EC) — classification is by underlying-fund <title>.
 */

/** One issuer share-class family's allocation snapshot. */
export interface TickerBlendRow {
  /** ALL tickers in the family (ETF + mutual-fund classes of the same strategy), UPPERCASE. */
  readonly family: readonly string[]
  readonly name: string
  readonly issuer: string
  /** Allocation percentages (0–100), the issuer's own figures (sum ~97–101; see header). */
  readonly stock: number
  readonly bond: number
  readonly cash: number
  /** The issuer product page / fact sheet the allocation was read from. */
  readonly citation: string
  /** False since the 2026-06-11 EDGAR pin pass (161/161 verified); a `true` row is an
   *  unpinned later addition awaiting the next pass. */
  readonly directionalUntilPinned: boolean
  /** Issuer-reported allocation as-of date (meaningful for balanced/TDF rows). */
  readonly asOf?: string
  /** Target-date funds only — the static-snapshot disclosure (D1) keys off this. */
  readonly tdfTargetYear?: number
}

