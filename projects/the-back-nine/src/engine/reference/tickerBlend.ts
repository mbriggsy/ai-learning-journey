/** The table's aggregate static-snapshot as-of (P3·U13 — the date-surface vintage clock).
 *  DERIVED as the max per-row `asOf` (ISO strings compare lexicographically), so a refresh
 *  pass that re-dates any row moves the aggregate with zero re-typing (single-source — the
 *  blend gate's discipline). Rows without `asOf` (pure index funds whose allocation is
 *  definitional) don't hold the aggregate back. Fails loud if NO row carries a date — an
 *  undated snapshot table has no vintage to stamp (burned/062: no plausible default). */
export const BLEND_SNAPSHOT_AS_OF: string = TICKER_BLEND_ROWS.reduce<string>((max, row) => {
  return row.asOf !== undefined && row.asOf > max ? row.asOf : max
}, '') || (() => {
  throw new Error('[tickerBlend] no row carries an asOf date — the snapshot vintage is unstampable')
})()

/** Eager module-level ticker index (ai-journey-stats/003 — never minted in render).
 *  A duplicate ticker across families is a transcription bug: fail loud at module
 *  init, never first-row-wins. */
const buildTickerIndex = (): ReadonlyMap<string, TickerBlendRow> => {
  const index = new Map<string, TickerBlendRow>()
  for (const row of TICKER_BLEND_ROWS) {
    for (const ticker of row.family) {
      const key = ticker.toUpperCase()
      if (index.has(key)) {
        throw new Error(`[tickerBlend] duplicate ticker ${key} across families — transcription bug`)
      }
      index.set(key, row)
    }
  }
  return index
}

const TICKER_INDEX = buildTickerIndex()

/** Case-insensitive family lookup. `undefined` = unrecognized — intake routes to the
 *  manual classifier (D1); never a default blend (burned/062). */
export const findBlendRow = (ticker: string): TickerBlendRow | undefined =>
  TICKER_INDEX.get(ticker.trim().toUpperCase())

/** Collapse a {stock, bond, cash} blend to the engine's single stock weight:
 *  `stock / (stock + bond + cash)` — the bond sleeve absorbs cash (v1, 2-asset
 *  engine; plan §5), and dividing by the ACTUAL sum distributes an issuer "other"
 *  sleeve pro-rata. Finiteness FIRST (insight 010): a NaN/negative component or a
 *  zero-sum blend is incomputable — throw, never a default (burned/062). */
export const stockWeightForBlend = (blend: {
  readonly stock: number
  readonly bond: number
  readonly cash: number
}): number => {
  const { stock, bond, cash } = blend
  if (![stock, bond, cash].every((x) => Number.isFinite(x) && x >= 0)) {
    throw new Error(
      `[tickerBlend] blend components must be finite and ≥ 0 (got ${stock}/${bond}/${cash}) — finiteness before any arithmetic (insight 010)`,
    )
  }
  const total = stock + bond + cash
  if (total <= 0) {
    throw new Error('[tickerBlend] blend sums to zero — nothing to collapse; no default (burned/062)')
  }
  return stock / total
}
